/**
 * Translate a text string using phrase substitution.
 * Applies longest matches first to avoid partial replacements.
 * Falls back to English for unmatched phrases.
 */
function translateText(text, lang) {
  if (!text || lang === 'en' || !PHRASES[lang]) return text;
  var phrases = PHRASES[lang];
  var result = text;
  for (var i = 0; i < phrases.length; i++) {
    var en = phrases[i][0];
    var tr = phrases[i][1];
    if (result.indexOf(en) !== -1) {
      result = result.split(en).join(tr);
    }
  }
  return result;
}

